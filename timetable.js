// ========================================
// DETECT CLASS TYPE
// ========================================

function getClassType(text) {

    const value = text.toUpperCase();

    if (
        value.includes("LAB") ||
        value.includes("TUTORIAL") ||
        value.includes("TUT")
    ) {
        return "lab";
    }

    if (value.includes("RESEARCH")) {
        return "research";
    }

    if (value.includes("JATI DIRI")) {
        return "activity";
    }

    return "lecture";
}


// ========================================
// GET SUBJECT NAME
// ========================================

function getSubject(text) {

    const value = text.toUpperCase();

    if (value.includes("CHEM")) {
        return "Chemistry";
    }

    if (value.includes("PHYS")) {
        return "Physics";
    }

    if (value.includes("BIO")) {
        return "Biology";
    }

    if (value.includes("LLA")) {
        return "LLA";
    }

    if (
        value.includes("LOGICAL") ||
        value.includes("MANTIK")
    ) {
        return "Logical Reasoning";
    }

    if (value.includes("STATISTICS")) {
        return "Statistics";
    }

    if (value.includes("RESEARCH")) {
        return "Research Skills";
    }

    if (value.includes("JATI DIRI")) {
        return "Jati Diri";
    }

    return text;
}


// ========================================
// CREATE CLASS CARD
// ========================================

function createClassCard(text, time) {

    const card =
        document.createElement("div");

    const classType =
        getClassType(text);

    card.className =
        `class-card ${classType}`;


    const subject =
        document.createElement("div");

    subject.className =
        "class-subject";

    subject.textContent =
        getSubject(text);


    const details =
        document.createElement("div");

    details.className =
        "class-details";

    details.textContent =
        text;


    card.appendChild(subject);

    card.appendChild(details);


    // Click class

    card.addEventListener(
        "click",
        function () {

            alert(
                getSubject(text) +
                "\n\n" +
                "Time: " +
                time +
                "\n\n" +
                text
            );

        }
    );


    return card;
}


// ========================================
// RENDER TIMETABLE
// ========================================

function renderTimetable() {

    const data =
        timetableData[currentSet];


    // Safety check

    if (!data) {

        timetableBody.innerHTML = `
            <tr>
                <td
                    colspan="6"
                    style="
                        padding:30px;
                        text-align:center;
                    "
                >
                    Timetable data for
                    ${currentSet}
                    is not available.
                </td>
            </tr>
        `;

        return;
    }


    // Clear old timetable

    timetableBody.innerHTML = "";


    // Update selected set

    selectedSetText.textContent =
        currentSet;


    // Days

    const dayNames = [

        ["mon", "Monday"],

        ["tues", "Tuesday"],

        ["wed", "Wednesday"],

        ["thurs", "Thursday"],

        ["fri", "Friday"]

    ];


    // Create every time row

    data.times.forEach(
        function (time, index) {


            const row =
                document.createElement("tr");


            // =================================
            // TIME COLUMN
            // =================================

            const timeCell =
                document.createElement("td");

            timeCell.className =
                "time-cell";

            timeCell.textContent =
                time;

            row.appendChild(timeCell);


            // =================================
            // DAY COLUMNS
            // =================================

            dayNames.forEach(
                function (day) {


                    const cell =
                        document.createElement("td");

                    cell.className =
                        "class-cell";


                    const classText =
                        data.days[day[0]][index];


                    // Empty period

                    if (!classText) {

                        cell.classList.add(
                            "empty-cell"
                        );

                    }


                    // Class exists

                    else {

                        const card =
                            createClassCard(
                                classText,
                                time
                            );

                        cell.appendChild(card);

                    }


                    row.appendChild(cell);

                }
            );


            timetableBody.appendChild(row);

        }
    );

}


// ========================================
// SET SELECTOR
// ========================================

setSelect.addEventListener(
    "change",
    function () {

        currentSet =
            this.value;

        renderTimetable();

    }
);


// ========================================
// START TIMETABLE
// ========================================

renderTimetable();
