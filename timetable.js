// ========================================
// CLASS TYPE
// ========================================

function classType(text) {

    const value =
        text.toUpperCase();

    if (
        value.includes("JATI DIRI")
    ) {
        return "type-activity";
    }

    if (
        value.includes("RESEARCH")
    ) {
        return "type-research";
    }

    if (
        value.includes("STATISTICS")
    ) {
        return "type-statistics";
    }

    if (
        value.includes("LOGICAL") ||
        value.includes("MANTIK")
    ) {
        return "type-reasoning";
    }

    if (
        value.includes("LLA")
    ) {
        return "type-lla";
    }

    if (
        value.includes("LAB") ||
        value.includes("TUT") ||
        value.includes("TUTORIAL")
    ) {
        return "type-lab";
    }

    return "type-lecture";
}


// ========================================
// SHORT SUBJECT NAME
// ========================================

function shortSubject(text) {

    const value =
        text.toUpperCase();

    if (
        value.includes("CHEM")
    ) {
        return "Chemistry";
    }

    if (
        value.includes("PHYS")
    ) {
        return "Physics";
    }

    if (
        value.includes("BIO")
    ) {
        return "Biology";
    }

    if (
        value.includes("LLA")
    ) {
        return "LLA";
    }

    if (
        value.includes("STATISTICS")
    ) {
        return "Statistics";
    }

    if (
        value.includes("RESEARCH")
    ) {
        return "Research Skills";
    }

    if (
        value.includes("LOGICAL") ||
        value.includes("MANTIK")
    ) {
        return "Logical Reasoning";
    }

    if (
        value.includes("JATI DIRI")
    ) {
        return "Jati Diri";
    }

    return text;
}


// ========================================
// CLASS DETAILS
// ========================================

function classDetails(text) {

    const spacedDash =
        text.indexOf(" - ");

    if (
        spacedDash !== -1
    ) {
        return text.substring(
            spacedDash + 3
        );
    }


    const looseDash =
        text.indexOf("-");

    if (
        looseDash !== -1
    ) {
        return text.substring(
            looseDash + 1
        ).trim();
    }


    return text;
}


// ========================================
// CREATE CLASS CARD
// ========================================

function makeClassCard(
    text,
    time
) {

    const card =
        document.createElement("div");

    card.className =
        `class-card ${classType(text)}`;


    const title =
        document.createElement("span");

    title.className =
        "class-title";

    title.textContent =
        shortSubject(text);


    const info =
        document.createElement("span");

    info.className =
        "class-info";

    info.textContent =
        classDetails(text);


    card.appendChild(
        title
    );

    card.appendChild(
        info
    );


    // Click a class to see full details

    card.addEventListener(
        "click",
        function () {

            alert(
                shortSubject(text) +
                "\n\n" +
                "Time: " +
                time +
                "\n\n" +
                text
            );

        }
    );


    return card;
}


// ========================================
// RENDER TIMETABLE
// ========================================

function renderTimetable(
    setName
) {

    const data =
        timetableData[setName];


    if (!data) {

        console.error(
            "Unknown timetable set:",
            setName
        );

        return;
    }


    // Clear old timetable

    timetableBody.innerHTML =
        "";


    // Update selected set text

    selectedSetText.textContent =
        setName;


    // Create every row

    data.times.forEach(
        function (
            time,
            rowIndex
        ) {

            const row =
                document.createElement(
                    "tr"
                );


            // =================================
            // TIME CELL
            // =================================

            const timeCell =
                document.createElement(
                    "td"
                );

            timeCell.className =
                "time-cell";

            timeCell.textContent =
                time;

            row.appendChild(
                timeCell
            );


            // =================================
            // MONDAY - FRIDAY
            // =================================

            dayKeys.forEach(
                function (
                    dayKey
                ) {

                    const cell =
                        document.createElement(
                            "td"
                        );

                    cell.className =
                        "class-cell";


                    // =================================
                    // BREAK
                    // =================================

                    if (
                        rowIndex === 5
                    ) {

                        cell.classList.add(
                            "break-cell"
                        );

                        cell.textContent =
                            "BREAK";

                    }


                    // =================================
                    // NORMAL SLOT
                    // =================================

                    else {

                        const text =
                            data.days[
                                dayKey
                            ][
                                rowIndex
                            ];


                        if (text) {

                            cell.classList.add(
                                "has-class"
                            );


                            const classCard =
                                makeClassCard(
                                    text,
                                    time
                                );


                            cell.appendChild(
                                classCard
                            );

                        }


                        else {

                            cell.classList.add(
                                "empty-cell"
                            );

                        }

                    }


                    row.appendChild(
                        cell
                    );

                }
            );


            timetableBody.appendChild(
                row
            );

        }
    );

}


