// Current selected set

let currentSet = "Set 1";


// HTML elements

const setSelect =
    document.getElementById("setSelect");

const selectedSetText =
    document.getElementById("selectedSetText");

const timetableBody =
    document.getElementById("timetableBody");


// ========================================
// DETECT CLASS TYPE
// ========================================

function getClassType(text) {

    const value = text.toUpperCase();

    if (
        value.includes("LAB") ||
        value.includes("TUTORIAL") ||
        value.includes("TUT")
    ) {
        return "lab";
    }

    if (
        value.includes("RESEARCH")
    ) {
        return "research";
    }

    if (
        value.includes("JATI DIRI")
    ) {
        return "activity";
    }

    return "lecture";
}


// ========================================
// GET SHORT SUBJECT NAME
// ========================================

function getSubject(text) {

    if (text.includes("CHEM")) {
        return "Chemistry";
    }

    if (text.includes("PHYS")) {
        return "Physics";
    }

    if (text.includes("BIO")) {
        return "Biology";
    }

    if (text.includes("LLA")) {
        return "LLA";
    }

    if (text.includes("LOGICAL")) {
        return "Logical Reasoning";
    }

    if (text.includes("STATISTICS")) {
        return "Statistics";
    }

    if (text.includes("RESEARCH")) {
        return "Research Skills";
    }

    if (text.includes("JATI DIRI")) {
        return "Jati Diri";
    }

    return text;
}


// ========================================
// CREATE CLASS CARD
// ========================================

function createClassCard(text, time) {

    const card =
        document.createElement("div");

    const type =
        getClassType(text);

    card.className =
        `class-card ${type}`;


    const subject =
        document.createElement("div");

    subject.className =
        "class-subject";

    subject.textContent =
        getSubject(text);


    const details =
        document.createElement("div");

    details.className =
        "class-details";

    details.textContent =
        text;


    card.appendChild(subject);
    card.appendChild(details);


    card.addEventListener("click", function () {

        alert(
            getSubject(text) +
            "\n\n" +
            time +
            "\n\n" +
            text
        );

    });


    return card;
}


// ========================================
// RENDER TIMETABLE
// ========================================

function renderTimetable() {

    const data =
        timetableData[currentSet];

    if (!data) {

        timetableBody.innerHTML = `
            <tr>
                <td colspan="6"
                    style="padding:30px;text-align:center;">
                    Timetable data for ${currentSet}
                    is not available yet.
                </td>
            </tr>
        `;

        return;
    }


    timetableBody.innerHTML = "";

    selectedSetText.textContent =
        currentSet;


    const dayNames = [
        ["mon", "Monday"],
        ["tues", "Tuesday"],
        ["wed", "Wednesday"],
        ["thurs", "Thursday"],
        ["fri", "Friday"]
    ];


    data.times.forEach(function(time, index) {

        const row =
            document.createElement("tr");


        // TIME

        const timeCell =
            document.createElement("td");

        timeCell.className =
            "time-cell";

        timeCell.textContent =
            time;

        row.appendChild(timeCell);


        // DAYS

        dayNames.forEach(function(day) {

            const cell =
                document.createElement("td");

            cell.className =
                "class-cell";


            const classText =
                data.days[day[0]][index];


            if (
                !classText ||
                classText === "R" ||
                classText === "E" ||
                classText === "H" ||
                classText === "A" ||
                classText === "T"
            ) {

                cell.classList.add("empty-cell");

            } else {

                const card =
                    createClassCard(
                        classText,
                        time
                    );

                cell.appendChild(card);

            }


            row.appendChild(cell);

        });


        timetableBody.appendChild(row);

    });

}


// ========================================
// SET SELECTOR
// ========================================

setSelect.addEventListener(
    "change",
    function () {

        currentSet =
            this.value;

        renderTimetable();

    }
);


// ========================================
// START
// ========================================

renderTimetable();
