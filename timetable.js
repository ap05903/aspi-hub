// START WITH SET 1
// ========================================

createSetSelector();

if (setSelector) {

    setSelector.value =
        "Set 1";

}

renderTimetable("Set 1");


// ========================================
// OPTIONAL: MOBILE SET BUTTONS
// ========================================

function switchTimetableSet(setName) {

    if (!timetableData[setName]) {
        return;
    }

    if (setSelector) {

        setSelector.value =
            setName;

    }

    renderTimetable(setName);

}

    
