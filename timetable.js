// ========================================
// GET ELEMENTS
// ========================================

const timetableContainer =
    document.getElementById("timetable");

const setSelector =
    document.getElementById("setSelector");


// ========================================
// CREATE SET SELECTOR
// ========================================

function createSetSelector() {

    if (!setSelector) {
        console.warn("setSelector not found.");
        return;
    }

    setSelector.innerHTML = "";

    Object.keys(timetableData).forEach(setName => {

        const option =
            document.createElement("option");

        option.value = setName;
        option.textContent = setName;

        setSelector.appendChild(option);

    });

}


// ========================================
// RENDER TIMETABLE
// ========================================

function renderTimetable(setName) {

    if (!timetableContainer) {
        console.warn("Timetable container not found.");
        return;
    }

    const data =
        timetableData[setName];

    if (!data) {
        console.warn("No timetable found for:", setName);
        return;
    }

    timetableContainer.innerHTML = "";


    // ========================================
    // TABLE
    // ========================================

    const table =
        document.createElement("table");

    table.className =
        "timetable-table";


    // ========================================
    // HEADER
    // ========================================

    const thead =
        document.createElement("thead");

    const headerRow =
        document.createElement("tr");


    const timeHeader =
        document.createElement("th");

    timeHeader.textContent =
        "Time";

    timeHeader.className =
        "time-header";

    headerRow.appendChild(timeHeader);


    dayLabels.forEach(day => {

        const th =
            document.createElement("th");

        th.textContent = day;

        th.className =
            "day-header";

        headerRow.appendChild(th);

    });


    thead.appendChild(headerRow);

    table.appendChild(thead);


    // ========================================
    // BODY
    // ========================================

    const tbody =
        document.createElement("tbody");


    data.times.forEach((time, index) => {

        const row =
            document.createElement("tr");


        // Time column

        const timeCell =
            document.createElement("td");

        timeCell.textContent =
            time;

        timeCell.className =
            "time-cell";

        row.appendChild(timeCell);


        // Day columns

        dayNames.forEach(dayName => {

            const cell =
                document.createElement("td");

            cell.className =
                "class-cell";


            const classText =
                data.days[dayName][index];


            // ========================================
            // BREAK
            // ========================================

            if (index === 5) {

                cell.classList.add("break-cell");

                cell.textContent =
                    "BREAK";

            }


            // ========================================
            // CLASS
            // ========================================

            else if (classText) {

                cell.classList.add("has-class");

                const classDiv =
                    document.createElement("div");

                classDiv.className =
                    "class-content";


                // Split subject from lecturer/room
                // when possible

                const separatorIndex =
                    classText.indexOf(" - ");


                if (separatorIndex !== -1) {

                    const subject =
                        classText.substring(
                            0,
                            separatorIndex
                        );

                    const details =
                        classText.substring(
                            separatorIndex + 3
                        );


                    const subjectElement =
                        document.createElement("strong");

                    subjectElement.textContent =
                        subject;


                    const detailsElement =
                        document.createElement("span");

                    detailsElement.textContent =
                        details;


                    classDiv.appendChild(
                        subjectElement
                    );

                    classDiv.appendChild(
                        detailsElement
                    );

                } else {

                    classDiv.textContent =
                        classText;

                }


                cell.appendChild(classDiv);

            }


            // ========================================
            // EMPTY
            // ========================================

            else {

                cell.classList.add("empty-cell");

            }


            row.appendChild(cell);

        });


        tbody.appendChild(row);

    });


    table.appendChild(tbody);

    timetableContainer.appendChild(table);

}


// ========================================
// SET SELECTOR CHANGE
// ========================================

if (setSelector) {

    setSelector.addEventListener(
        "change",
        function () {

            renderTimetable(
                this.value
            );

        }
    );

}


