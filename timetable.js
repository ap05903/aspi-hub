// ========================================
// RENDER TIMETABLE
// ========================================

function renderTimetable(setName) {

    const data =
        timetableData[setName];

    if (!data) {
        console.error("Timetable not found:", setName);
        return;
    }

    if (!timetableBody) {
        console.error("timetableBody not found.");
        return;
    }


    // Clear old rows

    timetableBody.innerHTML = "";


    // Update selected set text

    if (selectedSetText) {

        selectedSetText.textContent =
            setName;

    }


    // ========================================
    // CREATE EACH TIME ROW
    // ========================================

    data.times.forEach((time, index) => {

        const row =
            document.createElement("tr");


        // ====================================
        // TIME
        // ====================================

        const timeCell =
            document.createElement("td");

        timeCell.className =
            "time-cell";

        timeCell.textContent =
            time;

        row.appendChild(timeCell);


        // ====================================
        // MONDAY - FRIDAY
        // ====================================

        dayNames.forEach(dayName => {

            const cell =
                document.createElement("td");

            cell.className =
                "class-cell";


            // =================================
            // BREAK
            // =================================

            if (index === 5) {

                cell.classList.add("break-cell");

                cell.innerHTML =
                    `<span class="break-text">BREAK</span>`;

            }


            // =================================
            // CLASS
            // =================================

            else {

                const classText =
                    data.days[dayName][index];


                if (classText) {

                    cell.classList.add(
                        "has-class"
                    );


                    // ---------------------------------
                    // Work out class type
                    // ---------------------------------

                    const upperText =
                        classText.toUpperCase();


                    if (
                        upperText.includes("LECTURE")
                    ) {

                        cell.classList.add(
                            "lecture"
                        );

                    }
                    else if (
                        upperText.includes("LAB") ||
                        upperText.includes("TUT")
                    ) {

                        cell.classList.add(
                            "lab"
                        );

                    }
                    else if (
                        upperText.includes("RESEARCH")
                    ) {

                        cell.classList.add(
                            "research"
                        );

                    }
                    else if (
                        upperText.includes("JATI") ||
                        upperText.includes("ACTIVITY")
                    ) {

                        cell.classList.add(
                            "activity"
                        );

                    }


                    // ---------------------------------
                    // Class content
                    // ---------------------------------

                    const content =
                        document.createElement("div");

                    content.className =
                        "class-content";


                    const separator =
                        classText.indexOf(" - ");


                    if (separator !== -1) {

                        const subject =
                            classText.substring(
                                0,
                                separator
                            );

                        const details =
                            classText.substring(
                                separator + 3
                            );


                        const subjectElement =
                            document.createElement(
                                "strong"
                            );

                        subjectElement.textContent =
                            subject;


                        const detailsElement =
                            document.createElement(
                                "span"
                            );

                        detailsElement.textContent =
                            details;


                        content.appendChild(
                            subjectElement
                        );

                        content.appendChild(
                            detailsElement
                        );

                    }
                    else {

                        content.textContent =
                            classText;

                    }


                    cell.appendChild(content);

                }


                // =================================
                // EMPTY CELL
                // =================================

                else {

                    cell.classList.add(
                        "empty-cell"
                    );

                }

            }


            row.appendChild(cell);

        });


        timetableBody.appendChild(row);

    });

}


