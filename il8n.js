// 1. Dapatkan bahasa pilihan dari LocalStorage (Default ke Bahasa Melayu 'ms')
export const currentLang = localStorage.getItem('pintar_lang') || 'ms';

// 2. Fungsi Mengaplikasikan Terjemahan ke atas Elemen HTML yang mempunyai atribut `data-i18n`
export function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        
        if (translations[currentLang] && translations[currentLang][key]) {
            const translatedText = translations[currentLang][key];
            
            // Jika elemen ialah input/textbox, tukar placeholder
            if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                element.placeholder = translatedText;
            } else {
                element.textContent = translatedText;
            }
        }
    });
}

// 3. Fungsi Tukar Bahasa
export function setLanguage(langCode) {
    if (translations[langCode]) {
        localStorage.setItem('pintar_lang', langCode);
        location.reload(); // Refresh halaman untuk kemaskini semua teks
    }
}

// Export fungsi ke 'window' supaya boleh dipanggil terus melalui Event HTML (cth: onchange/onclick)
window.setLanguage = setLanguage;

// 4. Jalankan menterjemah sebaik sahaja struktur DOM selesai dimuatkan
document.addEventListener('DOMContentLoaded', applyTranslations);
